-- Safe, additive feature upgrade for Cute Bunny. This does not delete existing data.
-- Run once in Supabase Dashboard > SQL Editor.

alter table public.profiles
  add column if not exists notification_preferences jsonb not null
    default '{"memories":true,"buddy":true}'::jsonb;

-- Usernames are still protected by the existing unique constraint and format check.
grant update (username, display_name, bio, theme, mascot, notification_preferences)
  on public.profiles to authenticated;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('photo','song','note','buddy')),
  memory_id bigint references public.memories(id) on delete cascade,
  message text not null check (char_length(message) between 1 and 180),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (recipient_id, actor_id, kind, memory_id, created_at)
);
create index if not exists notifications_recipient_recent
  on public.notifications(recipient_id, created_at desc);
alter table public.notifications enable row level security;
drop policy if exists "Read own notifications" on public.notifications;
create policy "Read own notifications" on public.notifications
  for select to authenticated using (recipient_id = (select auth.uid()));
drop policy if exists "Mark own notifications read" on public.notifications;
create policy "Mark own notifications read" on public.notifications
  for update to authenticated using (recipient_id = (select auth.uid()))
  with check (recipient_id = (select auth.uid()));
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;
grant usage, select on sequence public.notifications_id_seq to authenticated;

-- A memory notification is created once per existing follower, excluding its author.
create or replace function public.notify_followers_of_memory() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  activity text;
begin
  activity := case new.kind
    when 'photo' then ' shared a new photo with you.'
    when 'song' then ' added a new song to your music garden.'
    else ' left you a little message.'
  end;
  insert into public.notifications(recipient_id, actor_id, kind, memory_id, message)
  select f.follower_id, new.owner_id, new.kind, new.id,
         coalesce(p.display_name, p.username, 'Your friend') || activity
    from public.follows f
    join public.profiles p on p.id = new.owner_id
   where f.followed_id = new.owner_id
     and f.follower_id <> new.owner_id
     and coalesce((select pr.notification_preferences ->> 'memories'
                     from public.profiles pr where pr.id = f.follower_id), 'true') <> 'false';
  return new;
end;
$$;
drop trigger if exists memories_notify_followers on public.memories;
create trigger memories_notify_followers after insert on public.memories
  for each row execute function public.notify_followers_of_memory();

-- Buddy taps notify mutual friends only and are limited to one ping per 60 seconds.
create or replace function public.send_buddy_ping() returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  actor uuid := (select auth.uid());
  actor_name text;
  lines text[] := array['is here! Come say hello ♡','wants your attention ♡','says come here! ♡','is active in your little garden ♡'];
  line text;
begin
  if actor is null then raise exception 'Please sign in again.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(actor::text, 29));
  if exists (select 1 from public.notifications n
              where n.actor_id = actor and n.kind = 'buddy'
                and n.created_at > now() - interval '60 seconds') then
    return false;
  end if;
  if coalesce((select p.notification_preferences ->> 'buddy' from public.profiles p where p.id = actor), 'true') = 'false' then
    return false;
  end if;
  select coalesce(p.display_name, p.username, 'Your friend') into actor_name
    from public.profiles p where p.id = actor;
  line := lines[1 + floor(random() * array_length(lines, 1))::int];
  insert into public.notifications(recipient_id, actor_id, kind, message)
  select theirs.follower_id, actor, 'buddy', actor_name || ' ' || line
    from public.follows mine
    join public.follows theirs on theirs.followed_id = actor and theirs.follower_id = mine.followed_id
    join public.profiles recipient on recipient.id = theirs.follower_id
   where mine.follower_id = actor and theirs.follower_id <> actor
     and coalesce(recipient.notification_preferences ->> 'buddy', 'true') <> 'false';
  return found;
end;
$$;
revoke all on function public.send_buddy_ping() from public;
grant execute on function public.send_buddy_ping() to authenticated;

-- Enable Supabase Realtime for notifications if the publication exists.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables
                      where pubname = 'supabase_realtime'
                        and schemaname = 'public' and tablename = 'notifications') then
    alter publication supabase_realtime add table public.notifications;
  end if;
end;
$$;
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notifications') then
      alter publication supabase_realtime add table public.notifications;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'profiles') then
      alter publication supabase_realtime add table public.profiles;
    end if;
  end if;
end;
$$;
