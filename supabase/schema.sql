create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9_]{3,24}$'),
  display_name text not null check (char_length(display_name) between 1 and 60),
  bio text not null default '' check (char_length(bio) <= 300),
  theme text not null default 'rose' check (theme in ('rose','lavender','mint','sky')),
  mascot text not null default '🐰' check (mascot in ('🐰','🐱','🐻','🐸')),
  created_at timestamptz not null default now()
);
create table if not exists public.follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  followed_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, followed_id),
  check (follower_id <> followed_id)
);
create table if not exists public.memories (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('note','photo','song')),
  text text not null default '' check (char_length(text) <= 1000),
  file_name text not null default '',
  content_type text not null default '',
  storage_path text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists memories_owner_created on public.memories(owner_id, created_at desc);
create index if not exists follows_follower on public.follows(follower_id);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username, display_name)
  values (new.id, lower(new.raw_user_meta_data ->> 'username'), coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''), lower(new.raw_user_meta_data ->> 'username')))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.follows enable row level security;
alter table public.memories enable row level security;
drop policy if exists "Profiles visible to signed-in friends" on public.profiles;
create policy "Profiles visible to signed-in friends" on public.profiles for select to authenticated using (true);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
drop policy if exists "Read own follow edges" on public.follows;
create policy "Read own follow edges" on public.follows for select to authenticated using (follower_id = (select auth.uid()) or followed_id = (select auth.uid()));
drop policy if exists "Follow as yourself" on public.follows;
create policy "Follow as yourself" on public.follows for insert to authenticated with check (follower_id = (select auth.uid()));
drop policy if exists "Unfollow as yourself" on public.follows;
create policy "Unfollow as yourself" on public.follows for delete to authenticated using (follower_id = (select auth.uid()));
drop policy if exists "Read own and followed memories" on public.memories;
create policy "Read own and followed memories" on public.memories for select to authenticated using (owner_id = (select auth.uid()) or exists (select 1 from public.follows f where f.follower_id = (select auth.uid()) and f.followed_id = memories.owner_id));
drop policy if exists "Create own memories" on public.memories;
create policy "Create own memories" on public.memories for insert to authenticated with check (owner_id = (select auth.uid()));
drop policy if exists "Delete own memories" on public.memories;
create policy "Delete own memories" on public.memories for delete to authenticated using (owner_id = (select auth.uid()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
