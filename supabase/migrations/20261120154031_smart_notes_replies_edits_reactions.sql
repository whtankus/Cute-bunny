-- Smart Notes messaging: replies, immutable edit history, reversible edits and richer reactions.
alter table public.memories
  add column if not exists reply_to_id bigint references public.memories(id) on delete set null,
  add column if not exists edited_at timestamptz;

create index if not exists memories_reply_to_id_idx
  on public.memories(reply_to_id) where reply_to_id is not null;

create table if not exists public.memory_edit_history (
  id bigint generated by default as identity primary key,
  memory_id bigint not null references public.memories(id) on delete cascade,
  editor_id uuid not null references public.profiles(id) on delete cascade,
  previous_text text not null check (char_length(previous_text) <= 1000),
  edited_at timestamptz not null default now()
);
create index if not exists memory_edit_history_memory_edited_idx
  on public.memory_edit_history(memory_id, edited_at desc);
alter table public.memory_edit_history enable row level security;
drop policy if exists "Read edit history for visible notes" on public.memory_edit_history;
create policy "Read edit history for visible notes"
on public.memory_edit_history for select to authenticated
using (
  exists (
    select 1 from public.memories m
    where m.id = memory_edit_history.memory_id
      and m.kind = 'note'
      and (
        m.owner_id = (select auth.uid())
        or exists (
          select 1 from public.follows f
          where f.follower_id = (select auth.uid())
            and f.followed_id = m.owner_id
        )
      )
  )
);
grant select on public.memory_edit_history to authenticated;

create or replace function private.capture_note_edit_history()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.kind = 'note' and new.kind = 'note' and old.text is distinct from new.text then
    insert into public.memory_edit_history(memory_id, editor_id, previous_text)
    values (old.id, old.owner_id, old.text);
    new.edited_at := pg_catalog.now();
  end if;
  return new;
end;
$$;
revoke all on function private.capture_note_edit_history() from public, anon, authenticated;
drop trigger if exists capture_note_edit_history on public.memories;
create trigger capture_note_edit_history before update of text on public.memories
for each row execute function private.capture_note_edit_history();

create or replace function public.restore_note_edit(p_history_id bigint)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_user_id uuid := auth.uid();
  v_memory_id bigint;
  v_previous_text text;
  v_edited_at timestamptz;
begin
  if v_user_id is null then raise exception 'Sign in to restore an edit.'; end if;
  select h.memory_id, h.previous_text into v_memory_id, v_previous_text
  from public.memory_edit_history h
  join public.memories m on m.id = h.memory_id
  where h.id = p_history_id and m.owner_id = v_user_id and m.kind = 'note';
  if not found then raise exception 'This edit is no longer available.'; end if;
  perform 1 from public.memories m
  where m.id = v_memory_id and m.owner_id = v_user_id and m.kind = 'note'
  for update;
  if not found then raise exception 'This message is no longer available.'; end if;
  update public.memories set text = v_previous_text
  where id = v_memory_id and owner_id = v_user_id and kind = 'note'
  returning edited_at into v_edited_at;
  return jsonb_build_object('ok', true, 'memory_id', v_memory_id,
    'text', v_previous_text, 'edited_at', v_edited_at);
end;
$$;
revoke all on function public.restore_note_edit(bigint) from public, anon;
grant execute on function public.restore_note_edit(bigint) to authenticated;

create table if not exists public.memory_reactions (
  memory_id bigint not null references public.memories(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null check (emoji in ('❤️','😂','🥰','😮','😢','👏')),
  created_at timestamptz not null default now(),
  primary key (memory_id, user_id, emoji)
);
create index if not exists memory_reactions_user_id_idx on public.memory_reactions(user_id);
alter table public.memory_reactions enable row level security;
drop policy if exists "Read reactions for visible memories" on public.memory_reactions;
create policy "Read reactions for visible memories"
on public.memory_reactions for select to authenticated
using (
  exists (
    select 1 from public.memories m
    where m.id = memory_reactions.memory_id
      and (
        m.owner_id = (select auth.uid())
        or exists (
          select 1 from public.follows f
          where f.follower_id = (select auth.uid())
            and f.followed_id = m.owner_id
        )
      )
  )
);
drop policy if exists "React to followed users notes" on public.memory_reactions;
create policy "React to followed users notes"
on public.memory_reactions for insert to authenticated
with check (
  user_id = (select auth.uid())
  and exists (
    select 1 from public.memories m
    where m.id = memory_reactions.memory_id
      and m.kind = 'note'
      and m.owner_id <> (select auth.uid())
      and exists (
        select 1 from public.follows f
        where f.follower_id = (select auth.uid())
          and f.followed_id = m.owner_id
      )
  )
);
drop policy if exists "Remove own note reactions" on public.memory_reactions;
create policy "Remove own note reactions"
on public.memory_reactions for delete to authenticated using (user_id = (select auth.uid()));
grant select, insert, delete on public.memory_reactions to authenticated;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'memory_reactions') then
    alter publication supabase_realtime add table public.memory_reactions;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'memories') then
    alter publication supabase_realtime add table public.memories;
  end if;
end $$;
